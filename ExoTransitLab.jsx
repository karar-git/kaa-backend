/* ── Light curve scatter plot (pure SVG) ────────────────────────────────── */
function LightCurveChart({ data }) {
  const W = 960;
  const H = 340;
  const M = { top: 22, right: 20, bottom: 42, left: 62 };
  const pw = W - M.left - M.right;
  const ph = H - M.top - M.bottom;

  const ys = data.pts.map((p) => p.y);
  const yMin = Math.min.apply(null, ys) - 0.003;
  const yMax = Math.max.apply(null, ys) + 0.003;

  const sx = (x) => M.left + ((x - data.lo) / (data.hi - data.lo)) * pw;
  const sy = (y) => M.top + (1 - (y - yMin) / (yMax - yMin)) * ph;

  const half = data.target.durationHr / 2;
  const ramp = data.target.durationHr * 0.19;

  const xTicks = [-2, -1.5, -1, -0.5, 0, 0.5, 1, 1.5, 2];
  const yTickCount = 5;
  const yTicks = Array.from(
    { length: yTickCount },
    (_, i) => yMin + ((i + 0.5) / yTickCount) * (yMax - yMin)
  );

  const binnedPath = data.binned
    .map((b, i) => `${i === 0 ? "M" : "L"}${sx(b.x).toFixed(1)},${sy(b.y).toFixed(1)}`)
    .join(" ");

  const contacts = [
    { x: -half, label: "Ingress", shift: 34 },
    { x: 0, label: "Mid-Transit", shift: 0 },
    { x: half, label: "Egress", shift: -34 },
  ];

  return (
    <svg
      viewBox={`0 0 ${W} ${H}`}
      className="h-auto w-full min-w-[720px]"
      role="img"
      aria-label={`Phase-folded light curve for ${
        data.target.id
      } showing a ${data.measuredDepth.toFixed(
        2
      )} percent transit dip between ingress and egress`}
    >
      {/* plot frame */}
      <rect
        x={M.left}
        y={M.top}
        width={pw}
        height={ph}
        fill="#020617"
        stroke="#1e293b"
        strokeWidth="1"
      />

      {/* transit window shading */}
      <rect
        x={sx(-half)}
        y={M.top}
        width={sx(half) - sx(-half)}
        height={ph}
        fill="#0ea5e9"
        opacity="0.06"
      />
      <rect
        x={sx(-half + ramp)}
        y={M.top}
        width={sx(half - ramp) - sx(-half + ramp)}
        height={ph}
        fill="#0ea5e9"
        opacity="0.05"
      />

      {/* grid + axis ticks */}
      {yTicks.map((t) => (
        <g key={`y${t}`}>
          <line
            x1={M.left}
            x2={M.left + pw}
            y1={sy(t)}
            y2={sy(t)}
            stroke="#1e293b"
            strokeWidth="1"
            strokeDasharray="2 4"
          />
          <text
            x={M.left - 10}
            y={sy(t) + 4}
            textAnchor="end"
            fill="#94a3b8"
            fontSize="11"
            fontFamily="ui-monospace, SFMono-Regular, Menlo, monospace"
          >
            {t.toFixed(4)}
          </text>
        </g>
      ))}
      {xTicks.map((t) => (
        <g key={`x${t}`}>
          <line
            x1={sx(t)}
            x2={sx(t)}
            y1={M.top}
            y2={M.top + ph}
            stroke="#1e293b"
            strokeWidth="1"
            strokeDasharray="2 4"
          />
          <text
            x={sx(t)}
            y={M.top + ph + 18}
            textAnchor="middle"
            fill="#94a3b8"
            fontSize="11"
            fontFamily="ui-monospace, SFMono-Regular, Menlo, monospace"
          >
            {t > 0 ? `+${t}` : t}
          </text>
        </g>
      ))}

      {/* raw flux points */}
      {data.pts.map((p, i) => (
        <circle
          key={i}
          cx={sx(p.x)}
          cy={sy(p.y)}
          r="2.1"
          fill={p.inTransit ? "#38bdf8" : "#60a5fa"}
          opacity="0.5"
        />
      ))}

      {/* binned mean curve */}
      <path d={binnedPath} fill="none" stroke="#34d399" strokeWidth="1.8" opacity="0.95" />
      {data.binned.map((b, i) => (
        <circle key={`b${i}`} cx={sx(b.x)} cy={sy(b.y)} r="2.6" fill="#34d399" />
      ))}

      {/* contact points: ingress / mid-transit / egress */}
      {contacts.map((c) => (
        <g key={c.label}>
          <line
            x1={sx(c.x)}
            x2={sx(c.x)}
            y1={M.top}
            y2={M.top + ph}
            stroke="#0ea5e9"
            strokeWidth="1"
            strokeDasharray="5 4"
            opacity="0.85"
          />
          <rect
            x={sx(c.x) + c.shift - 32}
            y={M.top + 6}
            width="64"
            height="17"
            rx="3"
            fill="#0f172a"
            stroke="#075985"
          />
          <text
            x={sx(c.x) + c.shift}
            y={M.top + 18}
            textAnchor="middle"
            fill="#38bdf8"
            fontSize="10"
            fontFamily="ui-monospace, SFMono-Regular, Menlo, monospace"
          >
            {c.label}
          </text>
        </g>
      ))}

      {/* axis labels */}
      <text
        x={M.left + pw / 2}
        y={H - 8}
        textAnchor="middle"
        fill="#94a3b8"
        fontSize="11"
        fontFamily="ui-monospace, SFMono-Regular, Menlo, monospace"
      >
        hours from predicted mid-transit
      </text>
      <text
        x={16}
        y={M.top + ph / 2}
        textAnchor="middle"
        fill="#94a3b8"
        fontSize="11"
        fontFamily="ui-monospace, SFMono-Regular, Menlo, monospace"
        transform={`rotate(-90 16 ${M.top + ph / 2})`}
      >
        normalised relative flux
      </text>
    </svg>
  );
}

/* ── Cadence micro-histogram ────────────────────────────────────────────── */
function CadenceHistogram({ hist }) {
  const { counts, max, lo, hi, bins } = hist;
  const step = (hi - lo) / bins;
  return (
    <div>
      <div className="flex h-36 items-end gap-1">
        {counts.map((c, i) => {
          const center = lo + (i + 0.5) * step;
          const nominalBin = Math.abs(center - SURVEY.nominalCadenceMin) < step;
          return (
            <div key={i} className="group flex flex-1 flex-col items-center justify-end">
              <span className="mb-1 font-mono text-[10px] text-slate-500 opacity-0 transition-opacity group-hover:opacity-100">
                {c}
              </span>
              <div
                className={[
                  "w-full rounded-t-sm transition-colors",
                  nominalBin ? "bg-sky-500" : "bg-slate-700 group-hover:bg-slate-600",
                ].join(" ")}
                style={{ height: `${Math.max(2, (c / max) * 110)}px` }}
                title={`${center.toFixed(2)} min · ${c} frames`}
              />
            </div>
          );
        })}
      </div>
      <div className="mt-2 flex justify-between border-t border-slate-800/80 pt-2 font-mono text-[11px] text-slate-400">
        <span>{lo.toFixed(2)} min</span>
        <span className="text-sky-400">nominal {SURVEY.nominalCadenceMin.toFixed(2)} min</span>
        <span>{hi.toFixed(2)} min</span>
      </div>
      <p className="mt-2 text-[12px] leading-relaxed text-slate-400">
        Inter-frame delta distribution across the current selection. The highlighted bin marks the
        commanded survey cadence; the tight unimodal profile confirms no dropped readout slots.
      </p>
    </div>
  );
}

