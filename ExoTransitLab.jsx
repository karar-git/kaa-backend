/* Cumulative on-sky coverage: union of per-session acquisition windows. */
const unionHours = (rows) => {
  if (!rows.length) return 0;
  const byKey = new Map();
  rows.forEach((r) => {
    const key = `${r.target}|${r.obsDate}|${r.session}`;
    const cur = byKey.get(key);
    if (!cur) byKey.set(key, [r.epochMs, r.epochMs]);
    else {
      if (r.epochMs < cur[0]) cur[0] = r.epochMs;
      if (r.epochMs > cur[1]) cur[1] = r.epochMs;
    }
  });
  const spans = [...byKey.values()].sort((a, b) => a[0] - b[0]);
  let total = 0;
  let [s, e] = spans[0];
  for (let i = 1; i < spans.length; i += 1) {
    const [ns, ne] = spans[i];
    if (ns <= e) e = Math.max(e, ne);
    else {
      total += e - s;
      s = ns;
      e = ne;
    }
  }
  total += e - s;
  return total / 3600000;
};

